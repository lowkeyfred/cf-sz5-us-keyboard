# Search SZ6 data region for key tables containing 0xF2/0xF3 (US-layout markers
# that SZ5 lacks). Also scan SZ5 for comparison. Report windows with set-2 density.
import sys

SET2 = set([
0x01,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0A,0x0B,0x0C,0x0D,0x0E,0x0F,
0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1A,0x1B,0x1C,0x1D,0x1E,0x1F,
0x21,0x22,0x23,0x24,0x25,0x26,0x27,0x28,0x29,0x2A,0x2B,0x2C,0x2D,0x2E,0x2F,
0x31,0x32,0x33,0x34,0x35,0x36,0x37,0x38,0x39,0x3A,0x3B,0x3C,0x3D,0x3E,0x3F,
0x41,0x42,0x43,0x44,0x45,0x46,0x47,0x48,0x49,0x4A,0x4B,0x4C,0x4D,0x4E,0x4F,
0x51,0x52,0x54,0x55,0x56,0x57,0x58,0x59,0x5A,0x5B,0x5C,0x5D,0x5E,0x5F,
0x61,0x62,0x63,0x64,0x65,0x66,0x67,0x68,0x69,0x6A,0x6B,0x6C,0x6D,0x6E,0x6F,
0x70,0x71,0x72,0x73,0x74,0x75,0x76,0x77,0x78,0x79,0x7A,0x7B,0x7C,0x7D,0x7E,
0x7F,0x80,0x81,0x82,0x83])

W = 128
MARK = (0xF2, 0xF3)

def scan(path, label):
    fw = open(path, 'rb').read()
    print('== %s (data 0x29000+, windows with 0xF2 or 0xF3, s2>=55) ==' % label)
    printed = 0
    for base in range(0x29000, len(fw) - W):
        win = fw[base:base + W]
        if MARK[0] not in win and MARK[1] not in win:
            continue
        s2 = sum(1 for b in win if b in SET2)
        if s2 < 55:
            continue
        # dedup sliding: skip if previous byte window also matched
        prev = fw[base - 1:base - 1 + W] if base > 0x29000 else b''
        if (MARK[0] in prev or MARK[1] in prev) and sum(1 for b in prev if b in SET2) >= 55:
            continue
        print('0x%06x s2=%d' % (base, s2))
        print('   ', ' '.join('%02x' % b for b in win))
        printed += 1
    if not printed:
        print('   (none)')

scan('ec_firmware.bin', 'SZ5')
scan('sz6/ec_sz6_firmware.bin', 'SZ6')
